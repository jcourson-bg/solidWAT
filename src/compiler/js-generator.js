/**
 * JS Generator — Compiles WATX AST to JavaScript glue code
 *
 * Generates JavaScript that:
 *   - Loads and instantiates the WASM module
 *   - Creates the SolidJS-inspired reactive signal system
 *   - Builds DOM elements for component templates
 *   - Wires up event handlers that call into WASM
 *   - Sets up reactive subscriptions for fine-grained DOM updates
 *
 * Architecture (SolidJS-inspired):
 *   - Signals are stored in WASM globals (fast, native i32/i64/f32/f64)
 *   - get/set operations go through WASM exported functions
 *   - The JS runtime wraps these with a dependency tracking system
 *   - Effects (subscriptions) automatically re-run when signals change
 *   - DOM updates are fine-grained: only the exact text node or attribute changes
 */

import { WatGenerator } from './wat-generator.js';

export class JsGenerator {
  constructor(ast) {
    this.ast = ast;
    this.watGen = new WatGenerator(ast);
    this.components = [];
    this.signals = [];
    this.exports = [];
    this.effects = [];
    this.memos = [];
    this.varCounter = 0;
  }

  /** Generate a unique variable name */
  uniqueVar(prefix) {
    return `${prefix}_${this.varCounter++}`;
  }

  generate() {
    // Populate the WAT generator's signal list by calling generate
    this.watGen.generate();

    // Collect all relevant nodes
    for (const node of this.ast.body) {
      switch (node.type) {
        case 'Signal':
          this.signals.push(node);
          break;
        case 'Component':
          this.components.push(node);
          break;
        case 'Export':
          this.exports.push(node);
          break;
        case 'Effect':
          this.effects.push(node);
          break;
        case 'Memo':
          this.memos.push(node);
          break;
      }
    }

    const signalInfo = this.watGen.getSignalInfo();
    return this.emitModule(signalInfo);
  }

  emitModule(signalInfo) {
    const lines = [];

    lines.push(`// Generated by WATX Compiler`);
    lines.push(`// WAT + HTML = WATX — A reactive UI framework in WebAssembly`);
    lines.push(``);
    lines.push(`import { createRuntime } from './watx-runtime.js';`);
    lines.push(``);
    lines.push(`export async function createApp(wasmUrl) {`);
    lines.push(`  const runtime = createRuntime();`);
    lines.push(`  const { createSignal, createEffect, batch, h, text, mount } = runtime;`);
    lines.push(``);

    // Load WASM
    lines.push(`  // Load WebAssembly module`);
    lines.push(`  const wasmResponse = await fetch(wasmUrl);`);
    lines.push(`  const wasmBytes = await wasmResponse.arrayBuffer();`);
    lines.push(`  const wasmModule = await WebAssembly.instantiate(wasmBytes, {});`);
    lines.push(`  const wasm = wasmModule.instance.exports;`);
    lines.push(``);

    // Create reactive signals backed by WASM
    lines.push(`  // Create reactive signals backed by WASM globals`);
    for (const sig of signalInfo) {
      const jsName = sig.name.slice(1);
      lines.push(`  const [${jsName}, set_${jsName}] = createSignal(`);
      lines.push(`    () => wasm.${sig.getterName}(),`);
      lines.push(`    (v) => wasm.${sig.setterName}(v),`);
      lines.push(`    ${sig.initialValue}`);
      lines.push(`  );`);
    }
    lines.push(``);

    // Generate component functions
    for (const comp of this.components) {
      lines.push(...this.emitComponent(comp, signalInfo));
      lines.push(``);
    }

    // Generate exports object
    lines.push(`  return {`);
    for (const exp of this.exports) {
      if (exp.kind === 'component') {
        const compName = exp.ref.slice(1);
        lines.push(`    ${exp.exportName}: render_${compName},`);
      }
    }
    lines.push(`    mount,`);
    lines.push(`    runtime,`);
    lines.push(`    wasm,`);
    lines.push(`  };`);
    lines.push(`}`);

    return lines.join('\n');
  }

  emitComponent(comp, signalInfo) {
    const lines = [];
    const name = comp.name.slice(1);
    lines.push(`  // Component: ${name}`);
    lines.push(`  function render_${name}() {`);

    // Generate the DOM tree — returns { lines, varName }
    const result = this.buildHtmlElement(comp.template, signalInfo, 2);
    lines.push(...result.lines);
    lines.push(`    return ${result.varName};`);

    lines.push(`  }`);
    return lines;
  }

  /**
   * Build an HTML element and all its children.
   * Returns { lines: string[], varName: string }
   * Does NOT include a return statement — caller decides when to return.
   */
  buildHtmlElement(node, signalInfo, indentLevel) {
    const pad = '  '.repeat(indentLevel);
    const lines = [];

    if (node.type === 'HtmlElement') {
      const varName = this.uniqueVar(`el_${node.tag}`);
      lines.push(`${pad}const ${varName} = h('${node.tag}');`);

      // Attributes
      for (const attr of node.attributes) {
        if (attr.value.type === 'StringLiteral') {
          lines.push(`${pad}${varName}.setAttribute('${attr.name}', '${this.escapeString(attr.value.value)}');`);
        } else if (attr.value.type === 'ReactiveExpr') {
          lines.push(...this.emitEventHandler(varName, attr.name, attr.value.expr, signalInfo, indentLevel));
        }
      }

      // Children
      for (const child of node.children) {
        if (child.type === 'HtmlElement') {
          const childResult = this.buildHtmlElement(child, signalInfo, indentLevel);
          lines.push(...childResult.lines);
          lines.push(`${pad}${varName}.appendChild(${childResult.varName});`);
        } else if (child.type === 'HtmlText') {
          const textVar = this.uniqueVar('txt');
          lines.push(`${pad}const ${textVar} = text('${this.escapeString(child.value)}');`);
          lines.push(`${pad}${varName}.appendChild(${textVar});`);
        } else if (child.type === 'ReactiveExpr') {
          lines.push(...this.emitReactiveChild(varName, child.expr, signalInfo, indentLevel));
        }
      }

      return { lines, varName };
    }

    // Fallback
    const varName = this.uniqueVar('node');
    lines.push(`${pad}const ${varName} = text('');`);
    return { lines, varName };
  }

  /**
   * Emit a reactive text child: {get $count}
   * Creates a text node and an effect that updates it when signals change.
   */
  emitReactiveChild(parentVar, expr, signalInfo, indentLevel) {
    const lines = [];
    const pad = '  '.repeat(indentLevel);
    const textVar = this.uniqueVar('reactive');

    const compiledExpr = this.watGen.compileReactiveExpr(expr);
    const jsExpr = this.compiledExprToJs(compiledExpr, signalInfo);

    lines.push(`${pad}const ${textVar} = text('');`);
    lines.push(`${pad}createEffect(() => {`);
    lines.push(`${pad}  ${textVar}.textContent = String(${jsExpr});`);
    lines.push(`${pad}});`);
    lines.push(`${pad}${parentVar}.appendChild(${textVar});`);

    return lines;
  }

  /**
   * Emit an event handler attribute: onClick={set $count (i32.add ...)}
   */
  emitEventHandler(elVar, attrName, expr, signalInfo, indentLevel) {
    const lines = [];
    const pad = '  '.repeat(indentLevel);

    // Map HTML event names to DOM events
    const eventMap = {
      'onClick': 'click',
      'onInput': 'input',
      'onChange': 'change',
      'onSubmit': 'submit',
      'onKeyDown': 'keydown',
      'onKeyUp': 'keyup',
      'onKeyPress': 'keypress',
      'onMouseOver': 'mouseover',
      'onMouseOut': 'mouseout',
      'onMouseDown': 'mousedown',
      'onMouseUp': 'mouseup',
      'onFocus': 'focus',
      'onBlur': 'blur',
      'onDblClick': 'dblclick',
    };

    const domEvent = eventMap[attrName];
    if (domEvent) {
      const compiledExpr = this.watGen.compileReactiveExpr(expr);
      const handlerJs = this.compiledExprToEventHandler(compiledExpr, signalInfo);

      lines.push(`${pad}${elVar}.addEventListener('${domEvent}', (e) => {`);
      lines.push(`${pad}  ${handlerJs}`);
      lines.push(`${pad}});`);
    } else {
      // Non-event reactive attribute
      const compiledExpr = this.watGen.compileReactiveExpr(expr);
      const jsExpr = this.compiledExprToJs(compiledExpr, signalInfo);
      lines.push(`${pad}createEffect(() => {`);
      lines.push(`${pad}  ${elVar}.setAttribute('${attrName}', String(${jsExpr}));`);
      lines.push(`${pad}});`);
    }

    return lines;
  }

  /**
   * Convert a compiled reactive expression to JS code for reading
   */
  compiledExprToJs(compiled, signalInfo) {
    switch (compiled.kind) {
      case 'signal_get':
        return `${compiled.signal}()`;

      case 'const':
        return `${compiled.value}`;

      case 'wasm_op':
        return this.emitWasmOp(compiled, signalInfo);

      case 'string':
        return `'${this.escapeString(compiled.value)}'`;

      case 'sexpr': {
        if (compiled.op === 'get' && compiled.args.length === 1) {
          const ref = compiled.args[0];
          if (ref.kind === 'ref') {
            const name = ref.name.slice(1);
            return `${name}()`;
          }
        }
        // Fallback: try to evaluate recursively
        if (compiled.op && compiled.args.length > 0) {
          return this.emitWasmOp({ kind: 'wasm_op', op: compiled.op, args: compiled.args }, signalInfo);
        }
        return `/* unhandled sexpr: ${compiled.op} */`;
      }

      case 'ref': {
        const name = compiled.name.slice(1);
        return `${name}()`;
      }

      default:
        return `/* unhandled: ${compiled.kind} */`;
    }
  }

  /**
   * Convert a compiled reactive expression to JS code for an event handler (setter)
   */
  compiledExprToEventHandler(compiled, signalInfo) {
    switch (compiled.kind) {
      case 'signal_set': {
        const setterFn = `set_${compiled.signal}`;
        if (compiled.value) {
          const valueJs = this.compiledExprToJs(compiled.value, signalInfo);
          return `${setterFn}(${valueJs});`;
        }
        // No explicit value — pass event value (for input handlers)
        return `${setterFn}(e.target.value);`;
      }

      case 'call': {
        const args = compiled.args.map(a => this.compiledExprToJs(a, signalInfo)).join(', ');
        return `wasm.${compiled.fn}(${args});`;
      }

      default:
        return `/* unhandled handler: ${compiled.kind} */`;
    }
  }

  /**
   * Emit a WASM operation as JavaScript
   * For i32.add(get $count, i32.const 1), we compute it in JS using the signal getter
   */
  emitWasmOp(compiled, signalInfo) {
    const op = compiled.op;
    const args = compiled.args.map(a => this.compiledExprToJs(a, signalInfo));

    // Map WASM ops to JS ops
    const opMap = {
      'i32.add': (a, b) => `(${a} + ${b})`,
      'i32.sub': (a, b) => `(${a} - ${b})`,
      'i32.mul': (a, b) => `(${a} * ${b})`,
      'i32.div_s': (a, b) => `(${a} / ${b} | 0)`,
      'i32.rem_s': (a, b) => `(${a} % ${b})`,
      'i32.and': (a, b) => `(${a} & ${b})`,
      'i32.or': (a, b) => `(${a} | ${b})`,
      'i32.xor': (a, b) => `(${a} ^ ${b})`,
      'i32.eq': (a, b) => `(${a} === ${b} ? 1 : 0)`,
      'i32.ne': (a, b) => `(${a} !== ${b} ? 1 : 0)`,
      'i32.lt_s': (a, b) => `(${a} < ${b} ? 1 : 0)`,
      'i32.gt_s': (a, b) => `(${a} > ${b} ? 1 : 0)`,
      'i32.le_s': (a, b) => `(${a} <= ${b} ? 1 : 0)`,
      'i32.ge_s': (a, b) => `(${a} >= ${b} ? 1 : 0)`,
      'i32.eqz': (a) => `(${a} === 0 ? 1 : 0)`,
      'i32.const': (a) => `${a}`,
      'i64.add': (a, b) => `(${a} + ${b})`,
      'i64.sub': (a, b) => `(${a} - ${b})`,
      'f32.add': (a, b) => `(${a} + ${b})`,
      'f32.sub': (a, b) => `(${a} - ${b})`,
      'f32.mul': (a, b) => `(${a} * ${b})`,
      'f32.div': (a, b) => `(${a} / ${b})`,
      'f64.add': (a, b) => `(${a} + ${b})`,
      'f64.sub': (a, b) => `(${a} - ${b})`,
      'f64.mul': (a, b) => `(${a} * ${b})`,
      'f64.div': (a, b) => `(${a} / ${b})`,
    };

    if (opMap[op]) {
      return opMap[op](...args);
    }

    // Fallback: call WASM directly for unknown ops
    return `wasm.${op.replace('.', '_')}(${args.join(', ')})`;
  }

  escapeString(s) {
    return s.replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\n/g, '\\n');
  }
}
